const DICT = { zh, en };
let saved = null;
try { saved = localStorage.getItem('tapeid-lang'); } catch {}
let cur = DICT[saved] ? saved : (navigator.language || '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
export const lang = () => cur;
export function setLang(l) { cur = l; try { localStorage.setItem('tapeid-lang', l); } catch {} }
export function t(key, vars = {}) {
  const s = DICT[cur][key] ?? DICT.zh[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}
